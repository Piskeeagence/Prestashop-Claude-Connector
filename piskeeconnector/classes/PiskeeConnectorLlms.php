/**
 * The llms.txt file of the shop (https://llmstxt.org): a short Markdown map
 * of the shop for AI assistants and answer engines. It lists what the shop
 * sells, its main categories and products, its policies and how to reach it,
 * with links. It is written at the root of the shop, next to robots.txt.
 */
class PiskeeConnectorLlms
{
    private const FILE = 'llms.txt';
    private const MARK = '<!-- llms.txt generated by Piskee for PrestaShop';

    /**
     * @param array<string, mixed> $args
     * @param array<string, mixed> $context
     *
     * @return array<string, mixed>
     */
    public function preview(array $args, array $context): array
    {
        $c = PiskeeConnectorHelper::boot($context);
        $refusal = self::refusal($c['id_shop']);
        $content = self::build($c['id_shop'], self::lang($c['id_shop']), $args);
        $current = self::current();

        return PiskeeConnectorHelper::json([
            'url' => self::url($c['id_shop']),
            'can_publish' => $refusal === '',
            'cannot_publish_because' => $refusal === '' ? null : $refusal,
            'already_published' => $current !== '',
            'existing_file_made_by_piskee' => $current !== '' && strpos($current, self::MARK) !== false,
            'characters' => Tools::strlen($content),
            'content' => $content,
        ]);
    }

    /**
     * @param array<string, mixed> $args
     * @param array<string, mixed> $context
     *
     * @return array<string, mixed>
     */
    public function publish(array $args, array $context): array
    {
        $c = PiskeeConnectorHelper::boot($context);
        $refusal = self::refusal($c['id_shop']);
        if ($refusal !== '') {
            return PiskeeConnectorHelper::error($refusal);
        }
        $content = self::build($c['id_shop'], self::lang($c['id_shop']), $args);
        $path = self::path();
        $current = self::current();
        $backup = '';
        if ($current !== '') {
            if ($current === $content) {
                return PiskeeConnectorHelper::json(['updated' => false, 'url' => self::url($c['id_shop']), 'note' => 'The published file is already up to date.']);
            }
            // Any previous version, ours or not, is kept before it is replaced.
            $dir = _PS_ROOT_DIR_ . '/var/piskeeconnector/llms';
            if (!is_dir($dir)) {
                @mkdir($dir, 0755, true);
                @file_put_contents($dir . '/index.php', "<?php\nheader('Location: ../');\nexit;\n");
                @file_put_contents($dir . '/.htaccess', "Require all denied\nDeny from all\n");
            }
            $backup = $dir . '/llms-' . date('Ymd-His') . '.txt';
            @file_put_contents($backup, $current);
        }
        $tmp = $path . '.tmp-' . bin2hex(random_bytes(4));
        if (@file_put_contents($tmp, $content) === false || !@rename($tmp, $path)) {
            @unlink($tmp);

            return PiskeeConnectorHelper::error('The file could not be written at the root of the shop (' . $path . '). The folder must be writable by the web server; the hosting provider or the merchant can fix that, or upload the content from preview_llms_txt by FTP.');
        }
        @chmod($path, 0644);

        return PiskeeConnectorHelper::json([
            'written' => true,
            'url' => self::url($c['id_shop']),
            'characters' => Tools::strlen($content),
            'previous_version_kept' => $backup !== '' ? 'var/piskeeconnector/llms/' . basename($backup) : null,
        ]);
    }

    /**
     * Why the file cannot be published for this shop, or '' when it can.
     */
    private static function refusal(int $idShop): string
    {
        if (Shop::isFeatureActive() && count(Shop::getShops(true, null, true)) > 1) {
            return 'This installation runs several shops that share one root folder, so a single llms.txt cannot describe them all. Show the merchant the preview instead.';
        }
        $root = _PS_ROOT_DIR_;
        $file = self::path();
        if (is_file($file) ? !is_writable($file) : !is_writable($root)) {
            return 'The root folder of the shop is not writable by the web server, so llms.txt cannot be written. The merchant can upload the preview by FTP.';
        }

        return '';
    }

    private static function path(): string
    {
        return rtrim(_PS_ROOT_DIR_, '/') . '/' . self::FILE;
    }

    private static function current(): string
    {
        $path = self::path();

        return is_file($path) ? (string) @file_get_contents($path) : '';
    }

    private static function url(int $idShop): string
    {
        $shop = new Shop($idShop);
        $ssl = (bool) Configuration::get('PS_SSL_ENABLED', null, null, $idShop);

        return ($ssl ? 'https://' . $shop->domain_ssl : 'http://' . $shop->domain) . rtrim((string) $shop->physical_uri, '/') . '/' . self::FILE;
    }

    /**
     * The file is written in the shop's default language.
     */
    private static function lang(int $idShop): int
    {
        return (int) Configuration::get('PS_LANG_DEFAULT', null, null, $idShop);
    }

    /**
     * @param array<string, mixed> $args
     */
    public static function build(int $idShop, int $idLang, array $args): string
    {
        $link = Context::getContext()->link ?: new Link();
        $db = Db::getInstance();
        $productLimit = max(0, min(200, (int) ($args['products_limit'] ?? 30)));
        $name = (string) Configuration::get('PS_SHOP_NAME', null, null, $idShop);
        $home = (string) $link->getPageLink('index', null, $idLang, null, false, $idShop);

        // Summary: what the merchant approved, else the home page meta description.
        $summary = trim((string) ($args['summary'] ?? ''));
        if ($summary === '') {
            $summary = (string) $db->getValue('SELECT ml.`description` FROM `' . _DB_PREFIX_ . 'meta` m
                INNER JOIN `' . _DB_PREFIX_ . 'meta_lang` ml ON ml.`id_meta` = m.`id_meta` AND ml.`id_lang` = ' . $idLang . ' AND ml.`id_shop` = ' . $idShop . '
                WHERE m.`page` = \'index\'', false);
        }
        $out = '# ' . self::clean($name) . "\n\n";
        if (trim($summary) !== '') {
            $out .= '> ' . self::clean(PiskeeConnectorHelper::excerpt($summary, 400)) . "\n\n";
        }
        $details = trim((string) ($args['details'] ?? ''));
        if ($details !== '') {
            $out .= self::clean(PiskeeConnectorHelper::excerpt($details, 1500)) . "\n\n";
        }
        $currency = new Currency((int) Configuration::get('PS_CURRENCY_DEFAULT', null, null, $idShop));
        $country = new Country((int) Configuration::get('PS_SHOP_COUNTRY_ID', null, null, $idShop), $idLang);
        $facts = ['- Website: ' . $home, '- Currency: ' . $currency->iso_code];
        if (Validate::isLoadedObject($country)) {
            $facts[] = '- Based in: ' . self::clean((string) $country->name);
        }
        $langs = [];
        foreach (Language::getLanguages(true, $idShop) as $lang) {
            $langs[] = (string) $lang['name'];
        }
        if (count($langs) > 1) {
            $facts[] = '- Languages: ' . self::clean(implode(', ', $langs));
        }
        $out .= implode("\n", $facts) . "\n\n";

        // Categories: the first two levels under the home category.
        $homeCategory = (int) Configuration::get('PS_HOME_CATEGORY', null, null, $idShop);
        $categories = $db->executeS('SELECT c.`id_category`, c.`id_parent`, cl.`name`, cl.`meta_description`, cl.`description`
            FROM `' . _DB_PREFIX_ . 'category` c
            INNER JOIN `' . _DB_PREFIX_ . 'category_shop` cs ON cs.`id_category` = c.`id_category` AND cs.`id_shop` = ' . $idShop . '
            INNER JOIN `' . _DB_PREFIX_ . 'category_lang` cl ON cl.`id_category` = c.`id_category` AND cl.`id_lang` = ' . $idLang . ' AND cl.`id_shop` = ' . $idShop . '
            WHERE c.`active` = 1 AND (c.`id_parent` = ' . $homeCategory . ' OR c.`id_parent` IN (SELECT `id_category` FROM `' . _DB_PREFIX_ . 'category` WHERE `id_parent` = ' . $homeCategory . ' AND `active` = 1))
            ORDER BY c.`nleft` ASC LIMIT 120', true, false) ?: [];
        // Tree order: each subcategory right under its own parent.
        $byParent = [];
        foreach ($categories as $row) {
            $byParent[(int) $row['id_parent']][] = $row;
        }
        $categories = [];
        foreach ($byParent[$homeCategory] ?? [] as $top) {
            $categories[] = $top;
            foreach ($byParent[(int) $top['id_category']] ?? [] as $child) {
                $categories[] = $child;
            }
        }
        if ($categories !== []) {
            $out .= "## Categories\n\n";
            foreach ($categories as $row) {
                $indent = (int) $row['id_parent'] === $homeCategory ? '' : '  ';
                $about = PiskeeConnectorHelper::excerpt((string) ($row['meta_description'] ?: $row['description']), 160);
                $out .= $indent . '- [' . self::clean((string) $row['name']) . '](' . $link->getCategoryLink((int) $row['id_category'], null, $idLang, null, $idShop) . ')'
                    . ($about !== '' ? ': ' . self::clean($about) : '') . "\n";
            }
            $out .= "\n";
        }

        // Products: best sellers first, then the newest, active and visible only.
        if ($productLimit > 0) {
            $rows = $db->executeS('SELECT p.`id_product`, pl.`name`, pl.`description_short`, pl.`meta_description`,
                    IFNULL(ps.`quantity`, 0) AS sold
                FROM `' . _DB_PREFIX_ . 'product` p
                INNER JOIN `' . _DB_PREFIX_ . 'product_shop` sh ON sh.`id_product` = p.`id_product` AND sh.`id_shop` = ' . $idShop . '
                INNER JOIN `' . _DB_PREFIX_ . 'product_lang` pl ON pl.`id_product` = p.`id_product` AND pl.`id_lang` = ' . $idLang . ' AND pl.`id_shop` = ' . $idShop . '
                LEFT JOIN `' . _DB_PREFIX_ . 'product_sale` ps ON ps.`id_product` = p.`id_product`
                WHERE sh.`active` = 1 AND sh.`visibility` IN (\'both\', \'catalog\')
                ORDER BY sold DESC, sh.`date_add` DESC LIMIT ' . $productLimit, true, false) ?: [];
            if ($rows !== []) {
                $out .= "## Products\n\n";
                foreach ($rows as $row) {
                    $id = (int) $row['id_product'];
                    $price = Product::getPriceStatic($id, true, null, 2, null, false, true, 1, false, null, null, null, $nothing, true, true, null, true);
                    $about = PiskeeConnectorHelper::excerpt((string) ($row['description_short'] ?: $row['meta_description']), 160);
                    $out .= '- [' . self::clean((string) $row['name']) . '](' . $link->getProductLink($id, null, null, null, $idLang, $idShop) . '): '
                        . number_format((float) $price, 2, '.', '') . ' ' . $currency->iso_code
                        . ($about !== '' ? '. ' . self::clean($about) : '') . "\n";
                }
                $out .= "\n";
            }
        }

        // Information pages: delivery, returns, terms, about...
        $pages = $db->executeS('SELECT c.`id_cms`, cl.`meta_title`, cl.`meta_description`
            FROM `' . _DB_PREFIX_ . 'cms` c
            INNER JOIN `' . _DB_PREFIX_ . 'cms_shop` cs ON cs.`id_cms` = c.`id_cms` AND cs.`id_shop` = ' . $idShop . '
            INNER JOIN `' . _DB_PREFIX_ . 'cms_lang` cl ON cl.`id_cms` = c.`id_cms` AND cl.`id_lang` = ' . $idLang . ' AND cl.`id_shop` = ' . $idShop . '
            WHERE c.`active` = 1 ORDER BY c.`position` ASC LIMIT 40', true, false) ?: [];
        $out .= "## Customer information\n\n";
        foreach ($pages as $row) {
            $about = PiskeeConnectorHelper::excerpt((string) $row['meta_description'], 160);
            $out .= '- [' . self::clean((string) $row['meta_title']) . '](' . $link->getCMSLink((int) $row['id_cms'], null, null, $idLang, $idShop) . ')'
                . ($about !== '' ? ': ' . self::clean($about) : '') . "\n";
        }
        $out .= '- [Contact](' . $link->getPageLink('contact', null, $idLang, null, false, $idShop) . ")\n\n";

        $out .= "## Optional\n\n";
        $out .= '- [New products](' . $link->getPageLink('new-products', null, $idLang, null, false, $idShop) . ")\n";
        $out .= '- [Best sales](' . $link->getPageLink('best-sales', null, $idLang, null, false, $idShop) . ")\n";
        $out .= '- [Prices drop](' . $link->getPageLink('prices-drop', null, $idLang, null, false, $idShop) . ")\n";
        if (is_file(_PS_ROOT_DIR_ . '/' . $idShop . '_index_sitemap.xml')) {
            $out .= '- [Sitemap](' . rtrim($home, '/') . '/' . $idShop . "_index_sitemap.xml)\n";
        }
        // Link targets must not contain spaces, or Markdown readers cut them.
        $out = (string) preg_replace_callback('/\]\(([^)]*)\)/', static function (array $m) {
            return '](' . str_replace(' ', '%20', $m[1]) . ')';
        }, $out);
        $out .= "\n" . self::MARK . ' on ' . date('Y-m-d') . " -->\n";

        return $out;
    }

    /**
     * One line of plain text, safe inside Markdown links and lists.
     */
    private static function clean(string $text): string
    {
        $text = html_entity_decode(strip_tags($text), ENT_QUOTES | ENT_HTML5, 'UTF-8');
        $text = (string) preg_replace('/\s+/u', ' ', $text);
        $text = str_replace(['[', ']', '<', '>'], ['(', ')', '', ''], $text);

        return trim($text);
    }
}
